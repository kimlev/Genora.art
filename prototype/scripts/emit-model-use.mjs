import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "src/lib/i18n/copy/model-use-source");
const aliases = JSON.parse(readFileSync(join(dir, "aliases.json"), "utf8"));
const locales = {};
for (const file of readdirSync(dir).filter((name) => name.endsWith(".json") && name !== "aliases.json")) {
  locales[file.replace(/\.json$/, "")] = JSON.parse(readFileSync(join(dir, file), "utf8"));
}

const order = ["ru", "en", "zh", "hi", "es", "fr", "ar", "pt", "de", "ja", "it", "ko", "tr", "pl", "nl", "sv", "cs", "el", "ro"];
const keys = Object.keys(locales.ru);
for (const locale of order) {
  if (!locales[locale]) throw new Error(`missing locale ${locale}`);
  const missing = keys.filter((key) => !locales[locale][key]);
  const extra = Object.keys(locales[locale]).filter((key) => !locales.ru[key]);
  if (missing.length || extra.length) {
    throw new Error(`${locale} missing=${missing.join(",")} extra=${extra.join(",")}`);
  }
}

const q = (value) => JSON.stringify(value);
const aliasBlock = Object.entries(aliases)
  .map(([key, value]) => `  ${q(key)}: ${q(value)},`)
  .join("\n");
const tableBlock = order
  .map((locale) => {
    const rows = keys.map((key) => `    ${q(key)}: ${q(locales[locale][key])},`).join("\n");
    return `  ${locale}: {\n${rows}\n  },`;
  })
  .join("\n");

const out = `/** Generated by scripts/emit-model-use.mjs from model-use-source/. Edit the JSON files, then re-emit. */
import type { Locale } from "@/lib/i18n/types";

const ALIASES: Record<string, string> = {
${aliasBlock}
};

const tables: Record<Locale, Record<string, string>> = {
${tableBlock}
};

function hasUse(id: string): boolean {
  return Boolean(tables.en[id]);
}

export function canonicalModelUseId(id: string): string {
  if (ALIASES[id]) return ALIASES[id];
  if (hasUse(id)) return id;
  const noDate = id.replace(/-\\d{8}$/, "");
  if (hasUse(noDate)) return noDate;
  const noBuild = id.replace(/-0309(?=-|$)/, "");
  if (hasUse(noBuild)) return noBuild;
  return id;
}

export function modelUseDescription(locale: Locale, id: string): string | null {
  const key = canonicalModelUseId(id);
  return tables[locale]?.[key] ?? tables.en[key] ?? null;
}
`;

const dest = join(root, "src/lib/i18n/copy/model-use.ts");
writeFileSync(dest, out);
console.log(`wrote ${dest} (${keys.length} models, ${order.length} locales)`);
