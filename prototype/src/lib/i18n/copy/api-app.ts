function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ""));
}

export function apiAppCopy(locale: Locale): ApiAppCopy {
  const item = templates[locale] ?? en;
  return {
    ...item,
    battleSource: (sessionId) => fill(item.battleSource, { id: sessionId }),
    imageAgentInputCount: (min, max) => fill(item.imageAgentInputCount, { min, max }),
    topUpMinimum: (amountUsd) => fill(item.topUpMinimum, { amount: amountUsd }),
    topUpMaximum: (amountUsd) => fill(item.topUpMaximum, { amount: amountUsd }),
  };
}
