export function publicModelDescription(locale: Locale, id: string, kind: "text" | "image" | "audio" | "video" | "music"): string {
  if (kind === "video" || kind === "music") {
    const media = mediaModelDescription(locale, id);
    if (media) return media;
  }
  if (kind !== "audio" && kind !== "video" && kind !== "music") {
    const use = modelUseDescription(locale, id);
    if (use) return use;
  }
  const table = roles[locale] ?? roles.en;
  return table[roleFor(id, kind === "music" ? "audio" : kind === "video" ? "image" : kind)];
}
