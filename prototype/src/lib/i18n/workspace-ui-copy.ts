export function workspaceUiCopy(locale: Locale): WorkspaceUiCopy {
  const base = copies[locale] ?? en;
  const models = { ...base.models };
  for (const id of Object.keys(models)) {
    const next = modelUseDescription(locale, id);
    if (next) models[id] = next;
  }
  return {
    ...base,
    models,
    sizes: { ...base.sizes, ...(videoSizeHints[locale] ?? videoSizeHints.en) },
    formats: { ...base.formats, ...(extraFormatHints[locale] ?? extraFormatHints.en) },
  };
}
